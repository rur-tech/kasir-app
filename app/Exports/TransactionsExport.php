<?php

namespace App\Exports;

use App\Models\Transaction;

use Maatwebsite\Excel\Concerns\FromCollection;
use Maatwebsite\Excel\Concerns\WithHeadings;

class TransactionsExport implements FromCollection, WithHeadings
{
    public function collection()
    {
        $rows = collect();

        $transactions = Transaction::with([
            'user',
            'branch',
            'paymentMethod',
            'details.product.category'
        ])->latest()->get();

        foreach ($transactions as $trx) {

            foreach ($trx->details as $detail) {

                $rows->push([

                    /*
                    |--------------------------------------------------------------------------
                    | NAMA LOGIN / KASIR
                    |--------------------------------------------------------------------------
                    */

                    'Nama Kasir' =>
                        $trx->user->name
                        ?? 'Admin',

                    /*
                    |--------------------------------------------------------------------------
                    | TANGGAL
                    |--------------------------------------------------------------------------
                    */

                    'Tanggal' =>
                        $trx->created_at
                            ->format('d-m-Y'),

                    /*
                    |--------------------------------------------------------------------------
                    | JAM
                    |--------------------------------------------------------------------------
                    */

                    'Jam' =>
                        $trx->created_at
                            ->format('H:i:s'),

                    /*
                    |--------------------------------------------------------------------------
                    | WAKTU LENGKAP
                    |--------------------------------------------------------------------------
                    */

                    'Waktu Lengkap' =>
                        $trx->created_at
                            ->format('d M Y H:i:s'),

                    /*
                    |--------------------------------------------------------------------------
                    | CABANG
                    |--------------------------------------------------------------------------
                    */

                    'Cabang' =>
                        $trx->branch->name
                        ?? '-',

                    /*
                    |--------------------------------------------------------------------------
                    | PRODUK
                    |--------------------------------------------------------------------------
                    */

                    'Produk' =>
                        $detail->product->name
                        ?? '-',

                    /*
                    |--------------------------------------------------------------------------
                    | BUNDLING
                    |--------------------------------------------------------------------------
                    */

                    'Bundling' =>
                        $detail->bundle_name
                        ?? '-',

                    /*
                    |--------------------------------------------------------------------------
                    | KATEGORI
                    |--------------------------------------------------------------------------
                    */

                    'Kategori' =>
                        $detail->product->category->name
                        ?? '-',

                    /*
                    |--------------------------------------------------------------------------
                    | QTY
                    |--------------------------------------------------------------------------
                    */

                    'Qty' =>
                        $detail->qty,

                    /*
                    |--------------------------------------------------------------------------
                    | HARGA
                    |--------------------------------------------------------------------------
                    */

                    'Harga' =>
                        $detail->price,

                    /*
                    |--------------------------------------------------------------------------
                    | SUBTOTAL
                    |--------------------------------------------------------------------------
                    */

                    'Subtotal' =>
                        $detail->subtotal,

                    /*
                    |--------------------------------------------------------------------------
                    | METODE PEMBAYARAN
                    |--------------------------------------------------------------------------
                    */

                    'Metode Pembayaran' =>
                        $trx->paymentMethod->name
                        ?? '-',

                    /*
                    |--------------------------------------------------------------------------
                    | DISKON
                    |--------------------------------------------------------------------------
                    */

                    'Diskon' =>
                        $trx->discount_total
                        ?? 0,

                    /*
                    |--------------------------------------------------------------------------
                    | GRAND TOTAL
                    |--------------------------------------------------------------------------
                    */

                    'Grand Total' =>
                        $trx->grand_total,

                    /*
                    |--------------------------------------------------------------------------
                    | BAYAR
                    |--------------------------------------------------------------------------
                    */

                    'Bayar' =>
                        $trx->cash
                        ?? 0,

                    /*
                    |--------------------------------------------------------------------------
                    | KEMBALIAN
                    |--------------------------------------------------------------------------
                    */

                    'Kembalian' =>
                        $trx->change
                        ?? 0,

                ]);
            }
        }

        return $rows;
    }

    public function headings(): array
    {
        return [

            'Nama Kasir',

            'Tanggal',

            'Jam',

            'Waktu Lengkap',

            'Cabang',

            'Produk',

            'Bundling',

            'Kategori',

            'Qty',

            'Harga',

            'Subtotal',

            'Metode Pembayaran',

            'Diskon',

            'Grand Total',

            'Bayar',

            'Kembalian',

        ];
    }
}